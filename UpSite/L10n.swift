enum L {
    static var current: AppLanguage {
        let raw = UserDefaults.standard.string(forKey: "language") ?? "system"
        switch AppLanguage(rawValue: raw) ?? .system {
        case .tr: return .tr
        case .en: return .en
        case .system:
            return (Locale.preferredLanguages.first ?? "en").lowercased().hasPrefix("tr") ? .tr : .en
        }
    }

    static var locale: Locale { Locale(identifier: current == .tr ? "tr_TR" : "en_US") }

    static func s(_ key: String, _ args: CVarArg...) -> String {
        let table = current == .tr ? tr : en
        let template = table[key] ?? tr[key] ?? key
        return args.isEmpty ? template : String(format: template, locale: locale, arguments: args)
    }

    static func percent(_ value: Double) -> String {
        let f = NumberFormatter()
        f.numberStyle = .percent
        f.locale = locale
        f.maximumFractionDigits = value >= 99.95 || value == 0 ? 0 : 1
        f.minimumFractionDigits = 0
        return f.string(from: NSNumber(value: value / 100)) ?? "\(value)"
    }

